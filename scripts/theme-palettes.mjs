const fmt = (n) => Number(n.toFixed(4)).toString();

let css = `/* GENERATED by scripts/theme-palettes.mjs — edit that script and re-run it, not this file.
 *
 * Each theme's replacement for Tailwind's colour variables. "classic" has no block: it is
 * Tailwind's own palette, the site as it looked before themes. */
`;

for (const [name, theme] of Object.entries(THEMES)) {
  const ramp = RAMPS[theme.scheme];
  const lines = [`  color-scheme: ${theme.scheme};`, `  --color-white: ${theme.white};`];
  for (const family of ["gray", "slate", "zinc", "neutral", "stone"]) {
    STEPS.forEach((step, i) => lines.push(`  --color-${family}-${step}: ${theme.gray[i]};`));
  }
  for (const hue of HUES) {
    const [h, peak] = theme.hues[hue];
    STEPS.forEach((step, i) => {
      lines.push(`  --color-${hue}-${step}: oklch(${fmt(ramp.L[i])} ${fmt(peak * ramp.C[i])} ${h});`);
    });
  }
  css += `\n:root[data-theme="${name}"] {\n${lines.join("\n")}\n}\n`;
}

const out = fileURLToPath(new URL("../app/theme-palettes.css", import.meta.url));
writeFileSync(out, css);
console.log(`wrote ${out}`);
