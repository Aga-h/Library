// Generates app/theme-palettes.css: each theme's replacement for Tailwind's colour variables.
//
// Tailwind v4 draws every colour utility from a CSS variable (`bg-gray-900` is
// `var(--color-gray-900)`), so a theme that redefines the variables restyles every page at once,
// without touching a component. The gray ramp sets a theme's character and is written out by hand;
// the hues are generated from one hue angle and peak chroma each, along a light ramp (50 is a pale
// tint, 900 is dark) or, for the dark themes, a mirrored one (50 is a dark tint, 700 is bright) —
// so a status pill like `bg-green-100 text-green-700` stays readable either way.
//
// Run after editing: node scripts/theme-palettes.mjs

